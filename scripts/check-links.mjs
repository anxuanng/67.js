// Checks that every relative link in the markdown and HTML files of the repository points at a file.
// Usage: node scripts/check-links.mjs
// A link resolves against its own folder, the repository root, `public/` or `docs/`, because the site serves
// the docs and the public folder from one origin.
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';

const repositoryRoot = process.cwd();
const skippedFolders = new Set(['node_modules', '.git', '.claude', 'build', 'dist', 'artifacts', 'coverage']);
const linkPattern = /(?:\]\(|href="|src=")([^)"#\s]+)/g;
// `release.json` is generated by `npm run prepare:release`. `./main.js` is an example path inside the guide.
const knownGeneratedLinks = new Set(['/release.json', './main.js']);
const externalPattern = /^(?:[a-z][a-z0-9+.-]*:|\/\/)/i;

function collectFiles(folder, found) {
  for (const name of readdirSync(folder)) {
    if (skippedFolders.has(name)) continue;
    const path = join(folder, name);
    if (statSync(path).isDirectory()) collectFiles(path, found);
    else if (/\.(md|html)$/.test(name)) found.push(path);
  }
  return found;
}

function linkResolves(file, link) {
  const withoutQuery = link.split('?')[0];
  const bases = [dirname(file), repositoryRoot, join(repositoryRoot, 'public'), join(repositoryRoot, 'docs')];
  const targets = withoutQuery.startsWith('/')
    ? bases.slice(1).map((base) => join(base, withoutQuery))
    : [resolve(dirname(file), withoutQuery), ...bases.slice(1).map((base) => join(base, withoutQuery))];
  return targets.some((target) => [target, `${target}.html`, `${target}.md`].some((candidate) => existsSync(candidate)));
}

const files = collectFiles(repositoryRoot, []);
const broken = [];
for (const file of files) {
  const text = readFileSync(file, 'utf8');
  for (const match of text.matchAll(linkPattern)) {
    const link = match[1];
    if (externalPattern.test(link) || knownGeneratedLinks.has(link)) continue;
    if (!linkResolves(file, link)) broken.push(`${relative(repositoryRoot, file)} -> ${link}`);
  }
}

console.log(`${files.length} files checked, ${broken.length} broken links`);
for (const entry of broken) console.log(entry);
process.exitCode = broken.length === 0 ? 0 : 1;
